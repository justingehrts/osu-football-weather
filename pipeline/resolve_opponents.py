"""Freeze the "next N opponents" list into config/opponents.yaml.

Why a frozen file: "next three opponents" changes every week as games are
played. If the nightly job re-computed it, the tracked teams (and the report)
would quietly shift. Instead we resolve once, write the file, and you edit/delete
it deliberately when you want to roll the window forward.
"""
from datetime import datetime, timezone

import yaml

from .cfbd import CfbdClient, pick
from .common import CONFIG_DIR, current_season, load_yaml

OUT = CONFIG_DIR / "opponents.yaml"


def run(force=False):
    if OUT.exists() and not force:
        print(f"{OUT.name} already exists; keeping it (use --force to re-resolve).")
        return
    cfg = load_yaml("teams.yaml")
    focal, n = cfg["focal_team"], cfg["next_opponents"]
    client = CfbdClient()
    season = current_season()
    games = []
    for st in ("regular", "postseason"):
        games += client.games(season, focal, st)
    upcoming = sorted((g for g in games if not g.get("completed")),
                      key=lambda g: pick(g, "startDate", "start_date") or "9999")
    opps = []
    for g in upcoming:
        home, away = pick(g, "homeTeam", "home_team"), pick(g, "awayTeam", "away_team")
        opp = away if home == focal else home
        if opp not in opps:
            opps.append(opp)
        if len(opps) == n:
            break
    if len(opps) < n:
        print(f"WARNING: only found {len(opps)} upcoming opponents for {season}.")
    OUT.write_text("# GENERATED by pipeline.resolve_opponents -- frozen on purpose.\n" +
                   yaml.safe_dump({"resolved_on": datetime.now(timezone.utc).date().isoformat(),
                                   "season": season, "opponents": opps}))
    print("Tracking opponents:", opps)


if __name__ == "__main__":
    import sys
    run(force="--force" in sys.argv)
