"""Build the tracked-team list from the focal team's schedule (config/teams.yaml -> season).

Costs ONE CFBD call (the league-wide /games for the season), and that same response is
reused by the games ingest, so it is not extra. Re-run with --force after changing
`season` or `focal_team` in config/teams.yaml.
"""
import sys
from datetime import datetime, timezone

import yaml

from .cfbd import CfbdClient, pick
from .common import CONFIG_DIR, current_season, load_bins, load_yaml

OUT = CONFIG_DIR / "opponents.yaml"


def opponents_from_games(games, focal):
    """-> (opponents in date order, non-FBS opponents)"""
    mine = sorted((g for g in games if focal in (pick(g, "homeTeam", "home_team"), pick(g, "awayTeam", "away_team"))),
                  key=lambda g: pick(g, "startDate", "start_date") or "9999")
    opps, non_fbs = [], []
    for g in mine:
        home_is_focal = pick(g, "homeTeam", "home_team") == focal
        opp = pick(g, "awayTeam", "away_team") if home_is_focal else pick(g, "homeTeam", "home_team")
        cls = pick(g, "awayClassification", "away_classification") if home_is_focal \
            else pick(g, "homeClassification", "home_classification")
        if opp and opp not in opps:
            opps.append(opp)
            if cls and cls != "fbs":
                non_fbs.append(opp)
    return opps, non_fbs


def run(force=False, client=None):
    cfg = load_yaml("teams.yaml")
    existing = load_yaml("opponents.yaml")
    if existing.get("season") == cfg["season"] and existing.get("all_opponents") and not force:
        print(f"{OUT.name} already resolved for {cfg['season']}; keeping it (use --force to redo).")
        return existing
    client = client or CfbdClient()
    ttl = load_bins()["cfbd"]["current_season_ttl_hours"] if cfg["season"] >= current_season() else None
    games = client.games(cfg["season"], "regular", ttl_hours=ttl)
    opps, non_fbs = opponents_from_games(games, cfg["focal_team"])
    if not opps:
        raise SystemExit(f"No {cfg['season']} games found for {cfg['focal_team']} -- check the spelling "
                         "in config/teams.yaml (must match CFBD's school name).")
    out = {"season": cfg["season"], "resolved_on": datetime.now(timezone.utc).date().isoformat(),
           "all_opponents": True, "opponents": opps, "non_fbs": non_fbs,
           # a hand-set choice; carried over so re-resolving never silently re-enables a team
           "deferred": [t for t in (existing.get("deferred") or []) if t in opps]}
    OUT.write_text("# GENERATED by pipeline.resolve_opponents from the focal team's schedule.\n"
                   "# Change config/teams.yaml (season / focal_team / extra_teams / exclude_teams) and re-run\n"
                   "# `python -m pipeline.resolve_opponents --force` instead of editing this file.\n" +
                   yaml.safe_dump(out, sort_keys=False))
    print(f"{cfg['focal_team']} {cfg['season']}: {len(opps)} opponents ({len(non_fbs)} non-FBS): {opps}")
    return out


if __name__ == "__main__":
    run(force="--force" in sys.argv)
